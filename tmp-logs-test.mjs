import { createClient } from "@supabase/supabase-js";
const URL = process.env.SUPABASE_URL, SVC = process.env.SUPABASE_SERVICE_ROLE_KEY, PUB = process.env.SUPABASE_PUBLISHABLE_KEY;
const shim = (key) => (i, init) => { const h = new Headers(init?.headers); if (key.startsWith("sb_") && h.get("Authorization") === `Bearer ${key}`) h.delete("Authorization"); h.set("apikey", key); return fetch(i, { ...init, headers: h }); };
const admin = createClient(URL, SVC, { auth: { persistSession: false }, global: { fetch: shim(SVC) } });
const PW = "TeamTest!2026aX", s = Date.now();
const oe = `o2.${s}@teamtest.temaro.io`, se = `s2.${s}@teamtest.temaro.io`;
const o = (await admin.auth.admin.createUser({ email: oe, password: PW, email_confirm: true })).data.user.id;
const st = (await admin.auth.admin.createUser({ email: se, password: PW, email_confirm: true })).data.user.id;
await admin.from("profiles").update({ subscription_tier: "standard" }).eq("id", o);
console.log("log insert:", JSON.stringify(await admin.from("logs").insert({ user_id: o, action_type: "missed_call_autotext", message_sent: "LOG-LINE-A" }).select("id, action_type, message_sent")));
await admin.from("team_members").insert({ business_owner_id: o, invited_email: se });
const c = createClient(URL, PUB, { auth: { persistSession: false }, global: { fetch: shim(PUB) } });
await c.auth.signInWithPassword({ email: se, password: PW });
console.log("claim:", (await c.rpc("claim_team_invites")).data);
console.log("staff logs read:", JSON.stringify(await c.from("logs").select("id, action_type, message_sent, user_id")));
for (const id of [o, st]) await admin.auth.admin.deleteUser(id);
